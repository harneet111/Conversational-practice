public class FOOD{
    public static void main(String[] args){
        int choice=3;
        switch (choice){
            case 1:
                System.out.println("pizza");
                break;
            case 2:
                System.out.println("Salad");
                break;
            case 3:
                System.out.println("Soup");
                break;
            case 4:
                System.out.println("Drink");
                break;
            default:
                System.out.println("invalid choice");
        }
    }
}